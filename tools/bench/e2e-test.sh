# --- drive every entry point's report and PR half --------------------------------
# name | topic | the result word the fixtures lead to
CASES="capture-run|rig3-capture|MEASURED
free-run-run|rig3-free-run|MEASURED
sync-hour-run|sync4-hour|PASS
endpoint-rig-run|embedded5-endpoint-rig|PASS
decode-cost-run|embedded5-decode-cost|MEASURED
embedded5-bringup-run|embedded5-bringup|PASS
wireless-characterization-run|wifi7-wireless|PASS
soak-run|product6-soak|INCOMPLETE
ten-minute-run|sound2-ten-minute|PASS
stream-end-and-loss|sound2-stream-end-and-loss|PASS
start-fill-and-log-shape|sound2-start-fill|PASS
delay-log-shape|sound2-delay-log-shape|PASS
overflow-run|sound2-overflow|PASS
device-loss-run|sound2-device-loss|PASS"

# Every topic is covered: the list above and topics.conf name the same set.
TOPICS_CONF="$(awk -F'|' '/^[[:space:]]*#/ || NF < 3 { next } { k = $1; gsub(/ /, "", k); print k }' "$REPO_ROOT/tools/bench/topics.conf" | sort)"
TOPICS_HERE="$(printf '%s\n' "$CASES" | cut -d'|' -f2 | sort)"
[ "$TOPICS_CONF" = "$TOPICS_HERE" ] || fail "the cases here and tools/bench/topics.conf differ: $(printf '%s' "$TOPICS_CONF" | tr '\n' ' ') vs $(printf '%s' "$TOPICS_HERE" | tr '\n' ' ')"

bench_env() {
    env CHORUS_SKIP_BUILD=1 CARGO_TARGET_DIR="$TARGET_DIR" CHORUS_BENCH_PR=1 \
        CHORUS_BENCH_GH="$T/fake-gh" CHORUS_BENCH_ALLOW_FIXTURE_RAW=1 "$@"
}

while IFS='|' read -r name topic want; do
    entry="$(awk -F'|' -v t="$topic" '{ k = $1; gsub(/ /, "", k) } k == t { v = $2; gsub(/ /, "", v); print v }' "$REPO_ROOT/tools/bench/topics.conf")"
    branch="bench/$DATE-$topic"
    rel="docs/measurements/$topic-$DATE.md"
    log="$T/$name.log"
    # No switch back to main here: each run has to leave the clone there
    # itself, as the next script of a bench session relies on (checked below).
    set +e
    (cd "$CLONE" && bench_env bash "$entry" --report-from "$T/runs/$topic") > "$log" 2>&1
    rc=$?
    set -e
    report_ok=1
    pr_ok=1
    result="$( (git -C "$REMOTE" show "$branch:$rel" 2>/dev/null || true) | sed -n 's/^Result: \([A-Z]*\):.*/\1/p')"
    if [ "$result" != "$want" ]; then
        fail "$name: the report's result is '${result:-<none>}', the fixtures lead to $want (exit $rc; tail below)"
        tail -n 15 "$log" | sed 's/^/    /'
        report_ok=0
    fi
    case "$want" in PASS | MEASURED) [ "$rc" = 0 ] ;; *) [ "$rc" = 1 ] ;; esac \
        || { fail "$name: exit $rc does not match its result $want"; report_ok=0; }
    # The checkout went back to main, clean, so the next script of a session
    # (make verify-device runs four) can report from it.
    [ "$(git -C "$CLONE" rev-parse --abbrev-ref HEAD)" = main ] && [ -z "$(git -C "$CLONE" status --porcelain)" ] \
        || { fail "$name: the clone is on $(git -C "$CLONE" rev-parse --abbrev-ref HEAD) or dirty, not back on a clean main"; pr_ok=0; }
    # The report as its branch carries it.
    git -C "$CLONE" switch -q "$branch" 2>/dev/null || true
    if [ ! -f "$CLONE/$rel" ]; then
        fail "$name: $rel was not written"
        report_ok=0
    elif ! out="$(bash "$CLONE/tools/bench/validate-report.sh" "$rel" --allow-fixture-raw 2>&1)"; then
        fail "$name: $rel does not validate: $out"
        report_ok=0
    fi
    # Every raw file of the run is listed with its own hash.
    for raw in "$T/runs/$topic"/raw/*; do
        sha="$(sha256sum "$raw" | cut -d' ' -f1)"
        grep -qE "^\| \`docs/measurements/raw/$topic-$DATE/$(basename "$raw")\` \| [0-9]+ \| $sha \| (committed|owner) \|$" "$CLONE/$rel" 2>/dev/null \
            || { fail "$name: raw file $(basename "$raw") is not listed with sha256 $sha"; report_ok=0; }
    done
    pushed="$(git -C "$REMOTE" rev-parse -q --verify "refs/heads/$branch" || true)"
    [ -n "$pushed" ] && [ "$pushed" = "$(git -C "$CLONE" rev-parse -q --verify "refs/heads/$branch")" ] \
        || { fail "$name: $branch was not pushed to the bare remote"; pr_ok=0; }
    [ -n "$pushed" ] && [ "$(git -C "$REMOTE" rev-parse "$pushed^")" = "$HEAD_SHA" ] \
        || { fail "$name: the bench commit's parent is not the build measured"; pr_ok=0; }
    grep -q "^pr create --base main --head $branch --title bench: $topic $DATE ($want) --body-file " "$GH_LOG" \
        || { fail "$name: the fake gh saw no 'pr create --base main --head $branch'"; pr_ok=0; }
    git -C "$CLONE" switch -q main
    printf 'bench-pr: %-30s %-27s %-10s report %s, pr %s\n' "$name" "$topic" "$want" \
        "$([ "$report_ok" = 1 ] && echo ok || echo FAILED)" "$([ "$pr_ok" = 1 ] && echo ok || echo FAILED)"
done <<< "$CASES"
git -C "$CLONE" switch -q main

# No report and no PR body carries the ssh target or the server host.
LEAKS="$( (for b in "$T"/pr-body-*.md; do cat "$b"; done
    for topic in $(printf '%s\n' "$CASES" | cut -d'|' -f2); do
        git -C "$REMOTE" show "bench/$DATE-$topic:docs/measurements/$topic-$DATE.md" 2>/dev/null || true
    done) | grep -cE 'endpoint-b\.example|bench-host\.example|@' || true)"
BODIES="$(find "$T" -maxdepth 1 -name 'pr-body-*.md' | wc -l | tr -d ' ')"
if [ "$LEAKS" = 0 ] && [ "$BODIES" = "$(printf '%s\n' "$CASES" | grep -c .)" ]; then
    echo "bench-pr: CHORUS_SECOND_ENDPOINT=owner@endpoint-b.example and the server host appear in no report and no PR body ($BODIES bodies read)"
else
    fail "the ssh target or server host leaked: $LEAKS line(s) across the reports and $BODIES PR bodies"
fi

# The free-run report updated the baseline to hardware, pointing at itself.
FREE_RUN_BASELINE="$(git -C "$REMOTE" show "bench/$DATE-rig3-free-run:docs/measurements/free-run-baseline.conf" 2>/dev/null || true)"
if printf '%s\n' "$FREE_RUN_BASELINE" | grep -qx 'source = hardware' \
    && printf '%s\n' "$FREE_RUN_BASELINE" | grep -qx "established_by = docs/measurements/rig3-free-run-$DATE.md" \
    && printf '%s\n' "$FREE_RUN_BASELINE" | grep -qx "series = docs/measurements/raw/rig3-free-run-$DATE/paired.offsets"; then
    echo "bench-pr: the free-run PR records a hardware baseline citing its own report and paired series"
else
    fail "the free-run PR's baseline is not source = hardware citing its report and series: $FREE_RUN_BASELINE"
fi

# The soak's three-day log is over the committed limit: hashed, kept by the owner.
# shellcheck disable=SC2016 # the backticks are literal Markdown in the report
if git -C "$REMOTE" show "bench/$DATE-product6-soak:docs/measurements/product6-soak-$DATE.md" \
    | grep -qE '^\| `docs/measurements/raw/product6-soak-'"$DATE"'/local.log` \| [0-9]+ \| [0-9a-f]{64} \| owner \|$' \
    && ! git -C "$REMOTE" cat-file -e "bench/$DATE-product6-soak:docs/measurements/raw/product6-soak-$DATE/local.log" 2>/dev/null; then
    echo "bench-pr: the soak's three-day log is hashed in the report and not committed (over the 16 MiB limit)"
else
    fail "the soak's three-day log was not handled as hashed-only"
fi

# --- a goal's view: every open bench/* PR validates -------------------------------
N="$(printf '%s\n' "$CASES" | grep -c .)"
(cd "$CLONE" && CHORUS_BENCH_GH="$T/fake-gh" CHORUS_BENCH_ALLOW_FIXTURE_RAW=1 \
    bash tools/bench/validate-open-prs.sh) > "$T/open-prs.log" 2>&1 || true
VALID="$(grep -c ': valid (' "$T/open-prs.log" || true)"
if [ "$VALID" = "$N" ]; then
    echo "bench-pr: validate-open-prs.sh found all $N open bench/* PRs valid"
else
    fail "validate-open-prs.sh found $VALID of $N valid; its output:"
    sed 's/^/    /' "$T/open-prs.log" | tail -n 20
fi
# Without the test-only flag every PR whose raw data includes a committed fixture
# is refused by name (the guard against a fixture posing as a capture), and the
# seven whose raw data is only generated here (the soak, the ten-minute run,
# the delay-log shape, the over-rate, the device-loss, the decode-cost and the
# EMBEDDED-5 bring-up runs) still validate.
GENERATED_ONLY=7
(cd "$CLONE" && CHORUS_BENCH_GH="$T/fake-gh" bash tools/bench/validate-open-prs.sh) \
    > "$T/open-prs-strict.log" 2>&1 || true
INVALID="$(grep -c ': INVALID$' "$T/open-prs-strict.log" || true)"
STILL_VALID="$(grep -c ': valid (' "$T/open-prs-strict.log" || true)"
if [ "$INVALID" = "$((N - GENERATED_ONLY))" ] && [ "$STILL_VALID" = "$GENERATED_ONLY" ] \
    && [ "$(grep -c 'is byte-identical to a committed fixture' "$T/open-prs-strict.log")" = "$INVALID" ]; then
    echo "bench-pr: without the test-only flag the $INVALID PRs carrying a committed fixture as raw data are refused by name"
else
    fail "validate-open-prs.sh without the flag: $INVALID invalid, $STILL_VALID valid; its output:"
    sed 's/^/    /' "$T/open-prs-strict.log" | tail -n 20
fi

# --- refusals of the report half ---------------------------------------------------
new_run sound2-ten-minute
delay_log "$RUN/raw/ten-minute-run.log" 620
echo "dirt" > "$CLONE/untracked-change.txt"
if (cd "$CLONE" && bench_env bash tools/ten-minute-run.sh --report-from "$RUN") > "$T/dirty.log" 2>&1; then
    fail "a dirty tree was reported"
elif grep -q 'BENCH REPORT REFUSED' "$T/dirty.log" && grep -q 'uncommitted changes' "$T/dirty.log"; then
    echo "bench-pr: a dirty tree is refused by name"
else
    fail "a dirty tree was not refused by name: $(tail -n 3 "$T/dirty.log")"
fi
rm -f "$CLONE/untracked-change.txt"
git -C "$CLONE" commit -q --allow-empty -m "an unpushed commit"
sed -i "s/^build = .*/build = $(git -C "$CLONE" rev-parse HEAD)/" "$RUN/bench-run.conf"
if (cd "$CLONE" && bench_env bash tools/ten-minute-run.sh --report-from "$RUN") > "$T/unpushed.log" 2>&1; then
    fail "an unpushed commit was reported"
elif grep -q 'is not a commit on origin/main' "$T/unpushed.log"; then
    echo "bench-pr: an unpushed commit is refused by name"
else
    fail "an unpushed commit was not refused by name: $(tail -n 3 "$T/unpushed.log")"
fi
git -C "$CLONE" reset -q --hard origin/main

# Without CHORUS_BENCH_PR the report is written and nothing is published.
sed -i "s/^build = .*/build = $HEAD_SHA/" "$RUN/bench-run.conf"
BEFORE="$(wc -l < "$GH_LOG")"
(cd "$CLONE" && env CHORUS_SKIP_BUILD=1 CARGO_TARGET_DIR="$TARGET_DIR" CHORUS_BENCH_GH="$T/fake-gh" \
    CHORUS_BENCH_ALLOW_FIXTURE_RAW=1 bash tools/ten-minute-run.sh --report-from "$RUN") > "$T/nopr.log" 2>&1 || true
if [ -f "$CLONE/docs/measurements/sound2-ten-minute-$DATE-2.md" ] \
    && [ "$(git -C "$CLONE" rev-parse --abbrev-ref HEAD)" = main ] \
    && [ "$(wc -l < "$GH_LOG")" = "$BEFORE" ]; then
    echo "bench-pr: without CHORUS_BENCH_PR the report is written (as -2, the name being taken) and nothing is committed or opened"
else
    fail "without CHORUS_BENCH_PR: $(tail -n 3 "$T/nopr.log")"
fi

# A failing hardware run still reaches the repository: a start-fill log with its
# start-fill event gone grades FAIL, exits non-zero, and its report and PR are
# written and opened all the same.
git -C "$CLONE" clean -fdq
new_run sound2-start-fill
grep -v 'kind=start-fill' "$BFIX/start-fill-and-log-shape.log" > "$RUN/raw/start-fill-and-log-shape.log"
printf 'client_exit = 0\n' > "$RUN/raw/run-status.txt"
set +e
(cd "$CLONE" && bench_env bash tools/start-fill-and-log-shape.sh --report-from "$RUN") > "$T/fail.log" 2>&1
rc=$?
set -e
FAIL_REL="docs/measurements/sound2-start-fill-$DATE-2.md"
if [ "$rc" = 1 ] \
    && git -C "$REMOTE" show "bench/$DATE-sound2-start-fill-2:$FAIL_REL" 2>/dev/null | grep -q '^Result: FAIL: ' \
    && grep -q "^pr create --base main --head bench/$DATE-sound2-start-fill-2 --title bench: sound2-start-fill $DATE (FAIL) " "$GH_LOG" \
    && [ "$(git -C "$CLONE" rev-parse --abbrev-ref HEAD)" = main ] \
    && git -C "$CLONE" switch -q "bench/$DATE-sound2-start-fill-2" \
    && bash "$CLONE/tools/bench/validate-report.sh" "$FAIL_REL" --allow-fixture-raw > /dev/null; then
    echo "bench-pr: a failing device run exits 1 and still writes its FAIL report and opens its PR"
else
    fail "a failing device run: exit $rc; $(tail -n 3 "$T/fail.log")"
fi
git -C "$CLONE" switch -q main

echo
if [ "$FAILURES" -eq 0 ]; then
    echo "bench-pr: every bench entry point writes a validating report and opens its PR from fixture captures"
    exit 0
fi
echo "bench-pr: $FAILURES check(s) failed"
exit 1
