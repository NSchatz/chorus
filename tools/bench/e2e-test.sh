#!/usr/bin/env bash
# The bench scripts' report-and-PR path, end to end, on fixture captures (K45).
#
# For EVERY hardware entry point in tools/bench/topics.conf: a run directory is
# built from committed fixtures (the chirp-pair captures and offsets series in
# fixtures/measure/, the client and server output of the device-class runs in
# fixtures/bench/, and delay logs and client output generated here in their
# formats),
# the entry point is driven with `--report-from` in a throwaway clone of this
# checkout whose `origin` is a local bare repository, with CHORUS_BENCH_PR=1 and
# a fake gh that records its arguments, and this asserts:
#   - the report file exists and validates (tools/bench/validate-report.sh)
#   - every raw file's sha256 in the report matches the run's file
#   - the branch bench/<date>-<topic> was pushed to the bare remote, carrying
#     the report, and the clone is back on a clean main (each case runs from
#     where the previous one left it, as the scripts of `make verify-device` do)
#   - the fake gh saw `pr create --base main --head bench/<date>-<topic>`
# and then that tools/bench/validate-open-prs.sh finds every one of those PRs
# valid, that the validator refuses a raw file equal to a fixture without the
# test-only flag, that the report half refuses a dirty tree and an unpushed
# commit, and that a FAIL run exits 1 with its report written and PR opened.
# The measure half is not run: it needs hardware and keeps refusing without it (tools/unrun-checks-are-visibly-unrun.sh). No device, no network,
# no real gh. Prints one line per entry point.
#
#   bash tools/bench/e2e-test.sh
set -euo pipefail

source "$(dirname "$0")/../lib.sh"
build_once

FIX="$REPO_ROOT/fixtures/measure"
DATE="2026-10-01"
T="$(mktemp -d "${TMPDIR:-/tmp}/chorus-bench-e2e-XXXXXX")"
# CHORUS_BENCH_E2E_KEEP=1 keeps the clone, the remote and the runs for a look.
[ "${CHORUS_BENCH_E2E_KEEP:-0}" = 1 ] || trap 'rm -rf "$T"' EXIT
FAILURES=0
fail() { printf 'FAIL %s\n' "$*"; FAILURES=$((FAILURES + 1)); }

# --- a clone of this checkout with a bare remote ---------------------------------
# The clone carries the files the report half reads (tools, config, fixtures,
# the measurements directory), as they are in this working tree, committed once
# and pushed to the bare remote as its main.
export GIT_AUTHOR_NAME="chorus bench test" GIT_AUTHOR_EMAIL="bench-test@example.invalid"
export GIT_COMMITTER_NAME="$GIT_AUTHOR_NAME" GIT_COMMITTER_EMAIL="$GIT_AUTHOR_EMAIL"
CLONE="$T/clone"
REMOTE="$T/remote.git"
mkdir -p "$CLONE"
git init -q --bare -b main "$REMOTE"
(cd "$REPO_ROOT" && git ls-files -c -o --exclude-standard -- tools config fixtures docs/measurements \
    | while IFS= read -r f; do [ -f "$f" ] && printf '%s\0' "$f"; done \
    | tar --null -T - -cf -) | tar -C "$CLONE" -xf -
git -C "$CLONE" init -q -b main
git -C "$CLONE" add -A
git -C "$CLONE" commit -q -m "bench e2e: snapshot of the checkout under test"
git -C "$CLONE" remote add origin "$REMOTE"
git -C "$CLONE" push -q -u origin main
HEAD_SHA="$(git -C "$CLONE" rev-parse HEAD)"

# --- a fake gh -------------------------------------------------------------------
GH_LOG="$T/gh-calls.log"
: > "$GH_LOG"
cat > "$T/fake-gh" <<EOF
#!/usr/bin/env bash
# Records every call; answers 'pr create' with a URL and 'pr list' with the PRs
# created so far, as "<n> <head>" lines (what --jq would print).
printf '%s\n' "\$*" >> "$GH_LOG"
# Keep each PR body, so the test can read what the owner's PR would say.
body=""; prev=""
for a in "\$@"; do [ "\$prev" = "--body-file" ] && body="\$a"; prev="\$a"; done
[ -n "\$body" ] && cp "\$body" "$T/pr-body-\$(grep -c '^pr create' "$GH_LOG").md"
case "\$1 \$2" in
    "pr create")
        n=\$(grep -c '^pr create' "$GH_LOG")
        echo "https://github.invalid/chorus/pull/\$n" ;;
    "pr list")
        grep '^pr create' "$GH_LOG" | sed -n 's/.*--head \([^ ]*\).*/\1/p' | awk '{ print NR, \$1 }' ;;
esac
EOF
chmod +x "$T/fake-gh"

# --- delay logs in the chorus delay log v1 format ---------------------------------
# <file> <seconds> [interval_us]: samples every interval (default 500 ms) for
# the whole run, all graded, delay held at the target, a clean summary.
delay_log() {
    local file="$1" seconds="$2" interval="${3:-500000}"
    awk -v s="$seconds" -v step="$interval" 'BEGIN {
        print "# chorus delay log v1"
        print "# generated by tools/bench/e2e-test.sh: NOT A MEASUREMENT"
        print "config min_us=60000 max_us=300000 start_fill_us=120000 device_target_us=120000 device=fixture rate_hz=48000 channels=2 sample_format=pcm_s16le frames_per_chunk=960 overflow_skew_ppm=2000"
        n = int(s * 1000000 / step)
        for (i = 0; i <= n; i++) printf "sample mono_us=%d delay_us=120000 occupancy_us=140000 graded=1\n", i * step
        span = n * step
        frames = int(span / 1000000 * 48000)
        printf "summary graded_span_us=%d graded_samples=%d delay_min_us=120000 delay_max_us=120000 margin_to_min_us=60000 margin_to_max_us=180000 underruns=0 discarded_overflow=0 discarded_late=0 discarded_duplicate=0 discarded_malformed=0 frames_written=%d frames_played=%d nominal_frames=%d\n", span, n + 1, frames, frames, frames
    }' > "$file"
}

# The owner runs the rig scripts with the second endpoint as an ssh target and
# may name the server host; neither may reach a report or a PR body (K27).
export CHORUS_SECOND_ENDPOINT="owner@endpoint-b.example" CHORUS_SERVER_HOST="bench-host.example"

# A run directory as the measure half leaves one.
new_run() {
    local topic="$1"
    RUN="$T/runs/$topic"
    mkdir -p "$RUN/raw"
    {
        printf 'topic = %s\n' "$topic"
        printf 'entry_point = %s\n' "$(awk -F'|' -v t="$topic" '{ k = $1; gsub(/ /, "", k) } k == t { v = $2; gsub(/ /, "", v); print v }' "$REPO_ROOT/tools/bench/topics.conf")"
        printf 'date = %s\n' "$DATE"
        printf 'build = %s\n' "$HEAD_SHA"
        printf 'criterion = the fixture-driven test of the report and PR path\n'
        printf 'device = fixture capture from fixtures/measure (NOT A MEASUREMENT)\n'
        # What a careless device note would carry: the scrub has to take it out.
        printf 'device = second endpoint %s, served from %s\n' "$CHORUS_SECOND_ENDPOINT" "$CHORUS_SERVER_HOST"
    } > "$RUN/bench-run.conf"
}

new_run rig3-capture
