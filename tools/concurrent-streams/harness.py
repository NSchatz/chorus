#!/usr/bin/env python3
"""The concurrent-streams measurement's helper (tools/concurrent-streams-run.sh, proposal
P11, decision K76): what K independent streams cost a running chorus-server in CPU and
memory, read off /proc.

Standard library only, plus the pinned reference programs for `media`. Subcommands:

- `media`: make the test signals. One 44.1 kHz 16-bit stereo signal (two sines and two
  independently seeded pink noises, one mix per channel, generated by the pinned ffmpeg's
  `sine` and `anoisesrc` sources, so it is the same on every run) encoded once per settled
  input format at a bitrate a household library really holds (the table ENCODES below).
  The programs come from the conda-forge prefix `make decode-fixtures` uses
  (tools/decode-fixtures/generate.py holds the pins and checks them; this command calls
  that check). Every program is used as a program; none of their source was opened.
- `serve`: a local HTTP media server (Range honoured, one thread per connection), the
  stand-in for a household's media server. It is another process, so its cost is not in
  the server's figures.
- `measure`: the scripted UPnP control point and the sampler. It finds the renderers the
  way a control point does (a search, each description), plays the same file on K of them
  (each renderer is one room, so each is its own stream through its own player thread),
  waits until every one is PLAYING and has settled, and reads /proc at both ends of a
  fixed window: per thread `utime + stime` (/proc/<pid>/task/<tid>/stat, clock ticks) and
  the scheduler's own run time (/proc/<pid>/task/<tid>/schedstat, nanoseconds, the finer
  figure), and for the process VmRSS, RssAnon, RssFile, VmHWM, VmSize (/proc/<pid>/status),
  Rss, Pss, Pss_Anon (/proc/<pid>/smaps_rollup) and the size of every mapping it may touch
  (/proc/<pid>/maps). Threads are told apart by the roles the
  server itself prints in its scheduling report (`thread role=<role> tid=<tid>`): the
  server does not name its threads for the kernel, and needs no change for this.
  With `--subscribe` it first subscribes, as one control point, to every service of every
  renderer and receives the events on a loopback callback.
- `probe`: the decoders alone: `chorus-server --probe-media` on each file (it decodes the
  file to its end and starts nothing else), the child's own CPU time from wait4. The
  `maxrss_kb` column it also writes is NOT the decoder's memory: it came out the same for
  every format (the forked interpreter's own peak before the exec), so no table uses it.
- `summary`: the report's tables (Markdown) from one or more runs' `windows.jsonl`.

Every interval here is CLOCK_MONOTONIC (`time.monotonic_ns`). Nothing here is timing
evidence: these are CPU and memory figures of a shared host.
"""

